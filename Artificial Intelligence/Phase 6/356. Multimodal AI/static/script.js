let selectedFile = null;

function showStatus(message, type = "") {
    statusBox.textContent = message;
    statusBox.className = "status " + type;
}

function validateFile(file) {
    if (!file) {
        return {
            valid: false,
            message: "Please select an image."
        };
    }

    const allowedTypes = [
        "image/jpeg",
        "image/png",
        "image/webp"
    ];

    if (!allowedTypes.includes(file.type)) {
        return {
            valid: false,
            message: "Only JPG, JPEG, PNG and WEBP images are allowed."
        };
    }

    const maxSize = 5 * 1024 * 1024;

    if (file.size > maxSize) {
        return {
            valid: false,
            message: "Image size must be less than 5 MB."
        };
    }

    return {
        valid: true,
        message: "Valid image."
    };
}

function selectFile(file) {
    const validation = validateFile(file);

    if (!validation.valid) {
        showStatus(validation.message, "error");
        return;
    }

    selectedFile = file;

    const reader = new FileReader();

    reader.onload = function(event) {
        previewImage.src = event.target.result;

        previewSection.classList.remove("hidden");

        imageInfo.innerHTML = `
            <strong>File:</strong>
            ${escapeHtml(file.name)}
            <br>
            <strong>Size:</strong>
            ${formatFileSize(file.size)}
            <br>
            <strong>Type:</strong>
            ${escapeHtml(file.type)}
        `;
    };

    reader.readAsDataURL(file);

    showStatus(
        "Image selected successfully.",
        "success"
    );
}

function formatFileSize(bytes) {
    if (bytes < 1024) {
        return bytes + " B";
    }

    if (bytes < 1024 * 1024) {
        return (bytes / 1024).toFixed(1) + " KB";
    }

    return (bytes / (1024 * 1024)).toFixed(2) + " MB";
}

function escapeHtml(value) {
    const div = document.createElement("div");
    div.textContent = value;
    return div.innerHTML;
}

/*
    Convert common Markdown generated by Gemini
    into HTML.

    Supported:
    **bold**
    *italic*
    # headings
    ## headings
    - unordered lists
    1. ordered lists
    `inline code`
    line breaks
*/

function markdownToHtml(markdown) {
    if (!markdown) {
        return "";
    }

    let text = escapeHtml(markdown);

    // Normalize line endings
    text = text.replace(/\r\n/g, "\n");
    text = text.replace(/\r/g, "\n");

    /*
        Headings
    */

    text = text.replace(
        /^### (.+)$/gm,
        "<h4>$1</h4>"
    );

    text = text.replace(
        /^## (.+)$/gm,
        "<h3>$1</h3>"
    );

    text = text.replace(
        /^# (.+)$/gm,
        "<h2>$1</h2>"
    );

    /*
        Bold + italic
        Do bold first so **text** is handled correctly.
    */

    text = text.replace(
        /\*\*(.+?)\*\*/g,
        "<strong>$1</strong>"
    );

    text = text.replace(
        /__(.+?)__/g,
        "<strong>$1</strong>"
    );

    text = text.replace(
        /(?<!\*)\*([^*\n]+)\*(?!\*)/g,
        "<em>$1</em>"
    );

    text = text.replace(
        /(?<!_)_([^_\n]+)_(?!_)/g,
        "<em>$1</em>"
    );

    /*
        Inline code
    */

    text = text.replace(
        /`([^`\n]+)`/g,
        "<code>$1</code>"
    );

    /*
        Convert unordered list items.

        Example:
        - First
        - Second
    */

    text = text.replace(
        /(?:^|\n)(?:[ \t]*[-*+] (.+)(?:\n|$))+/g,
        function(match) {
            const items = [];

            const lines = match
                .trim()
                .split("\n");

            lines.forEach(line => {
                const item = line.replace(
                    /^[ \t]*[-*+] (.+)$/,
                    "$1"
                );

                if (item !== line || line.startsWith("- ") ||
                    line.startsWith("* ") ||
                    line.startsWith("+ ")) {
                    items.push(
                        `<li>${item}</li>`
                    );
                }
            });

            if (items.length === 0) {
                return match;
            }

            return "\n<ul>" +
                items.join("") +
                "</ul>\n";
        }
    );

    /*
        Convert ordered lists.

        Example:
        1. First
        2. Second
    */

    text = text.replace(
        /(?:^|\n)(?:[ \t]*\d+\. (.+)(?:\n|$))+/g,
        function(match) {
            const items = [];

            const lines = match
                .trim()
                .split("\n");

            lines.forEach(line => {
                const item = line.replace(
                    /^[ \t]*\d+\. (.+)$/,
                    "$1"
                );

                if (item !== line) {
                    items.push(
                        `<li>${item}</li>`
                    );
                }
            });

            if (items.length === 0) {
                return match;
            }

            return "\n<ol>" +
                items.join("") +
                "</ol>\n";
        }
    );

    /*
        Markdown horizontal rule
    */

    text = text.replace(
        /^---+$/gm,
        "<hr>"
    );

    /*
        Convert remaining new lines into HTML breaks.

        Don't add <br> immediately around block elements.
    */

    text = text.replace(
        /\n{2,}/g,
        "</p><p>"
    );

    text = text.replace(
        /\n/g,
        "<br>"
    );

    /*
        Remove unnecessary paragraph wrapping
        around block elements.
    */

    text = "<p>" + text + "</p>";

    text = text.replace(
        /<p>\s*(<h[234]>)/g,
        "$1"
    );

    text = text.replace(
        /(<\/h[234]>)\s*<\/p>/g,
        "$1"
    );

    text = text.replace(
        /<p>\s*(<ul>)/g,
        "$1"
    );

    text = text.replace(
        /(<\/ul>)\s*<\/p>/g,
        "$1"
    );

    text = text.replace(
        /<p>\s*(<ol>)/g,
        "$1"
    );

    text = text.replace(
        /(<\/ol>)\s*<\/p>/g,
        "$1"
    );

    text = text.replace(
        /<p>\s*(<hr>)/g,
        "$1"
    );

    text = text.replace(
        /(<hr>)\s*<\/p>/g,
        "$1"
    );

    return text;
}

imageInput.addEventListener(
    "change",
    function() {
        if (this.files.length > 0) {
            selectFile(this.files[0]);
        }
    }
);

dropArea.addEventListener(
    "dragover",
    function(event) {
        event.preventDefault();

        dropArea.classList.add("dragging");
    }
);

dropArea.addEventListener(
    "dragleave",
    function() {
        dropArea.classList.remove("dragging");
    }
);

dropArea.addEventListener(
    "drop",
    function(event) {
        event.preventDefault();

        dropArea.classList.remove("dragging");

        const files = event.dataTransfer.files;

        if (files.length > 0) {
            selectFile(files[0]);
        }
    }
);

document
    .querySelectorAll(".quick-prompt")
    .forEach(button => {
        button.addEventListener(
            "click",
            function() {
                promptInput.value =
                    this.dataset.prompt;
            }
        );
    });

async function analyzeImage() {
    if (!selectedFile) {
        showStatus(
            "Please select an image first.",
            "error"
        );

        return;
    }

    const prompt =
        promptInput.value.trim()
        || "Describe this image in detail.";

    const formData = new FormData();

    formData.append(
        "image",
        selectedFile
    );

    formData.append(
        "prompt",
        prompt
    );

    analyzeButton.disabled = true;

    showStatus(
        "AI is analyzing the image...",
        "loading"
    );

    resultSection.classList.remove(
        "hidden"
    );

    analysisBox.innerHTML =
        "<p>Analyzing image...</p>";

    try {
        const response = await fetch(
            "/analyze",
            {
                method: "POST",
                body: formData
            }
        );

        const data = await response.json();

        if (!response.ok || !data.success) {
            throw new Error(
                data.error ||
                "Image analysis failed."
            );
        }

        /*
            IMPORTANT:
            Use innerHTML + markdownToHtml()
            instead of textContent.

            This converts:
            **text**
            into:
            <strong>text</strong>
        */

        analysisBox.innerHTML =
            markdownToHtml(data.analysis);

        if (data.image_info) {
            imageInfo.innerHTML += `
                <br>
                <strong>Dimensions:</strong>
                ${data.image_info.width}
                ×
                ${data.image_info.height}
                <br>
                <strong>Format:</strong>
                ${escapeHtml(
                    data.image_info.format || ""
                )}
            `;
        }

        showStatus(
            "Image analyzed successfully.",
            "success"
        );

    } catch (error) {
        analysisBox.textContent =
            "Error: " + error.message;

        showStatus(
            error.message,
            "error"
        );

    } finally {
        analyzeButton.disabled = false;
    }
}

analyzeButton.addEventListener(
    "click",
    analyzeImage
);